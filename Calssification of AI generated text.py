# --------- Generate CBOW dataset: surroundings indices ---------
def generate_cbow_dataset(token_lists, window_size, word_to_index):
    surroundings = []
    targets = []

    for tokens in token_lists:
        if len(tokens) < 2 * window_size + 1:
            continue

        for i in range(window_size, len(tokens) - window_size):
            center_word = tokens[i]
            center_idx = word_to_index.get(center_word, word_to_index["<OOV>"])

            ctx_indices = []
            for j in range(i - window_size, i + window_size + 1):
                if j == i:
                    continue
                w = tokens[j]
                ctx_indices.append(word_to_index.get(w, word_to_index["<OOV>"]))

            surroundings.append(ctx_indices)
            targets.append(center_idx)

    surroundings = torch.tensor(surroundings, dtype=torch.long)
    targets = torch.tensor(targets, dtype=torch.long)
    return surroundings, targets

class CBOW(nn.Module):
    def __init__(self, vocab_size, embed_dim):
        super().__init__()
        # Learned lookup table instead of linear(one-hot)
        self.embedding = nn.Embedding(vocab_size, embed_dim)
        # After averaging embeddings → predict center word
        self.linear_out = nn.Linear(embed_dim, vocab_size, bias=False)

    def forward(self, idx_context):
        """
        idx_context: [batch, 2W]  integer word indices
        """
        emb = self.embedding(idx_context)    # [batch, 2W, D]
        avg = emb.mean(dim=1)                # [batch, D]
        out = self.linear_out(avg)           # [batch, vocab]
        return out

# --------- CBOW training epoch ---------
def train_cbow_epoch(model, loader, optimizer, loss_fn, vocab_size):
    model.train()
    total_loss = 0.0

    for surr, tar in loader:
        surr, tar = surr.to(device), tar.to(device)

        optimizer.zero_grad()
        logits = model(surr)        # NO one-hot → direct index lookup
        loss = loss_fn(logits, tar)
        loss.backward()
        optimizer.step()

        total_loss += loss.item() * surr.size(0)

    return total_loss / len(loader.dataset)

