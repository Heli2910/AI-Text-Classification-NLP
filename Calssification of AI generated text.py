def run_mnb(
    train_texts, train_labels,
    test_texts,  test_labels,
    mode_name="TF-IDF baseline"
):
    """
    TF-IDF + MultinomialNB with GridSearchCV over alpha.
    """
    print(f"\n==============================")
    print(f"MultinomialNB GridSearchCV ({mode_name})")
    print(f"==============================")

    pipe = Pipeline([
        ("tfidf", TfidfVectorizer(
            max_features=50000,
            ngram_range=(1, 2)
        )),
        ("clf", MultinomialNB())
    ])

    param_grid = {
        "clf__alpha": [0.1, 0.5, 1.0]
    }

    grid = GridSearchCV(
        estimator=pipe,
        param_grid=param_grid,
        cv=3,
        scoring="accuracy",
        n_jobs=-1,
        verbose=1
    )

    grid.fit(train_texts, train_labels)

    print("\n[MNB] Best params:", grid.best_params_)
    print("[MNB] Best CV accuracy:", grid.best_score_)

    best_model = grid.best_estimator_
    test_pred = best_model.predict(test_texts)

    # Performance metrics
    acc = accuracy_score(test_labels, test_pred)
    f1  = f1_score(test_labels, test_pred)
    rec = recall_score(test_labels, test_pred)

    print(f"\n[MNB] TEST Accuracy: {acc:.4f}")
    print(f"[MNB] TEST F1-score: {f1:.4f}")
    print(f"[MNB] TEST Recall:   {rec:.4f}")

    print("\n[MNB] Classification Report:")
    print(classification_report(test_labels, test_pred, digits=4))

    return {
        "best_params": grid.best_params_,
        "cv_best_acc": grid.best_score_,
        "test_acc":    acc,
        "test_f1":     f1,
        "test_rec":    rec,
        "test_pred":   test_pred,
        "model":       best_model
    }

def run_logistic(
    train_texts, train_labels,
    test_texts,  test_labels,
    mode_name="TF-IDF baseline"
):
    """
    TF-IDF + Logistic Regression with GridSearchCV over C and class_weight.
    """
