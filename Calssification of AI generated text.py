def create_word_to_embedding(vocab_list, model, word_to_index):
    # embedding.weight: [V, D]
    W = model.embedding.weight.detach().cpu()

    word_to_embedding = {}
    for w in vocab_list:
        idx = word_to_index.get(w, word_to_index["<OOV>"])
        word_to_embedding[w] = W[idx]

    word_to_embedding["<OOV>"] = W[word_to_index["<OOV>"]]
    return word_to_embedding

# --------- Build sentence/document embeddings ---------
def get_doc_embedding(tokens, word_to_embedding, emb_dim):
    vecs = []

    for w in tokens:
        if w in word_to_embedding:
            vecs.append(word_to_embedding[w])
        else:
            vecs.append(word_to_embedding["<OOV>"])

    if not vecs:
        return torch.zeros(emb_dim)

    mat = torch.stack(vecs, dim=0)
    return mat.mean(dim=0)   # average word vectors

def build_doc_embeddings(token_lists, word_to_embedding, emb_dim):
    embs = []
    for toks in token_lists:
        embs.append(get_doc_embedding(toks, word_to_embedding, emb_dim).numpy())
    return np.vstack(embs).astype(np.float32)

