class MLPClassifier(nn.Module):
    def __init__(self, in_dim, hid=256, drop=0.3):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(in_dim, hid),
            nn.ReLU(),
            nn.Dropout(drop),
            nn.Linear(hid, hid//2),
            nn.ReLU(),
            nn.Dropout(drop),
            nn.Linear(hid//2, 2)
        )
    def forward(self, x):
        return self.net(x)

